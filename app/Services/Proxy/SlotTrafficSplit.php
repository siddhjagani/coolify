<?php

namespace App\Services\Proxy;

use App\Models\Application;
use App\Models\Server;
use Illuminate\Support\Collection;
use Symfony\Component\Yaml\Yaml;

/**
 * The proxy routing that splits the traffic of a production application between the applications of its slot group by
 * weight. Like the maintenance pages, it is generated from the database for each server: a dynamic Traefik file, or
 * blocks in the base Caddyfile. A sticky cookie keeps each visitor on one slot.
 *
 * The routing only adds routes with a higher priority than the container labels. When it cannot work (Traefik cannot
 * find the service of a stopped slot), the proxy drops it and production serves all the traffic through its labels.
 */
class SlotTrafficSplit
{
    public const TRAEFIK_FILE = 'coolify-slots.yaml';

    /**
     * The production applications on the server that split their traffic, with the applications that get a share.
     *
     * @return Collection<int, array{production: Application, members: Collection<int, Application>}>
     */
    public static function splits(Server $server): Collection
    {
        if ($server->isSwarm()) {
            return collect();
        }

        return $server->primaryApplications()
            ->filter(fn (Application $application) => $application->slot_of_id === null
                && ! $application->is_maintenance_enabled
                && $application->settings?->slot_traffic_weight !== null)
            ->map(fn (Application $production) => [
                'production' => $production,
                'members' => $production->slotGroup()
                    ->filter(fn (Application $member) => (int) $member->settings?->slot_traffic_weight > 0
                        && $member->destination?->server_id === $server->id)
                    ->values(),
            ])
            ->filter(fn (array $split) => $split['members']->count() > 1)
            ->values();
    }

    /**
     * A router for each router of the production labels, with the same rule, entry points, TLS, and middlewares (so
     * redirects and basic auth still apply), a higher priority, and a weighted service over the services of the slots.
     */
    public static function traefikConfiguration(Server $server): ?string
    {
        $routers = [];
        $services = [];
        foreach (self::splits($server) as ['production' => $production, 'members' => $members]) {
            $children = $members
                ->map(fn (Application $member) => ($service = self::traefikServiceName($member)) === null ? null : [
                    'name' => "{$service}@docker",
                    'weight' => (int) $member->settings->slot_traffic_weight,
                ])
                ->filter()
                ->values();
            if ($children->count() < 2) {
                continue;
            }

            $weighted = "coolify-slots-{$production->uuid}";
            $services[$weighted] = ['weighted' => [
                'services' => $children->all(),
                'sticky' => ['cookie' => ['name' => self::cookieName($production), 'httpOnly' => true, 'sameSite' => 'lax']],
            ]];
            foreach (self::traefikRouters($production) as $name => $router) {
                $routers["coolify-slots-{$name}"] = array_filter([
                    'entryPoints' => $router['entryPoints'],
                    'rule' => $router['rule'],
                    'middlewares' => $router['middlewares'],
                    'service' => $weighted,
                    'priority' => strlen($router['rule']) + 1,
                    'tls' => $router['tls'],
                ], fn ($value) => $value !== null && $value !== []);
            }
        }

        if ($routers === []) {
            return null;
        }

        return "# This file is generated by Coolify, do not edit it manually.\n\n".Yaml::dump([
            'http' => ['routers' => $routers, 'services' => $services],
        ], 12, 2);
    }

    /**
     * Caddy blocks for the site addresses of each production application. Each block is a `handle` with the path of
     * the domain, which Caddy runs before the `reverse_proxy` of the labels. The upstreams are the network aliases of
     * the applications, which are their UUIDs. A slot that does not answer is skipped for 30 seconds.
     *
     * @return array<string, list<string>> site address => blocks
     */
    public static function caddySites(Server $server): array
    {
        $sites = [];
        foreach (self::splits($server) as ['production' => $production, 'members' => $members]) {
            $upstreams = $members->map(fn (Application $member) => $member->uuid.':'.self::port($member))->implode(' ');
            $weights = $members->map(fn (Application $member) => (int) $member->settings->slot_traffic_weight)->implode(' ');
            foreach ($production->maintenanceCaddySites() as $index => $site) {
                $matcher = "@coolify-slots-{$production->uuid}-{$index}";
                $sites[$site['address']][] = implode("\n", [
                    "\t{$matcher} path {$site['path']}",
                    "\thandle {$matcher} {",
                    "\t\treverse_proxy {$upstreams} {",
                    "\t\t\tlb_policy cookie ".self::cookieName($production).' {',
                    "\t\t\t\tfallback weighted_round_robin {$weights}",
                    "\t\t\t}",
                    "\t\t\tlb_try_duration 5s",
                    "\t\t\tfail_duration 30s",
                    "\t\t}",
                    "\t}",
                ]);
            }
        }

        return $sites;
    }

    public static function cookieName(Application $production): string
    {
        return "coolify_slot_{$production->uuid}";
    }

    /**
     * The first service in the labels of the application: it sends traffic to its container.
     */
    private static function traefikServiceName(Application $application): ?string
    {
        foreach (generateLabelsApplication($application) as $label) {
            if (preg_match('/^traefik\.http\.services\.([A-Za-z0-9_-]+)\.loadbalancer\.server\.port=/', $label, $matches)) {
                return $matches[1];
            }
        }

        return null;
    }

    /**
     * @return array<string, array{rule: string, entryPoints: list<string>|null, middlewares: list<string>, tls: array<string, string>|null}>
     */
    private static function traefikRouters(Application $production): array
    {
        $options = [];
        foreach (traefikHostRulesWithoutIpv6Brackets(collect(generateLabelsApplication($production))) as $label) {
            if (preg_match('/^traefik\.http\.routers\.([A-Za-z0-9_-]+)\.([A-Za-z.]+)=(.*)$/', $label, $matches)) {
                $options[$matches[1]][strtolower($matches[2])] = $matches[3];
            }
        }

        $routers = [];
        foreach ($options as $name => $router) {
            if (blank($router['rule'] ?? null)) {
                continue;
            }
            $list = fn (?string $value): array => array_values(array_filter(array_map('trim', explode(',', (string) $value))));
            $routers[$name] = [
                'rule' => $router['rule'],
                'entryPoints' => isset($router['entrypoints']) ? $list($router['entrypoints']) : null,
                'middlewares' => array_map(fn (string $middleware) => str_contains($middleware, '@') ? $middleware : "{$middleware}@docker", $list($router['middlewares'] ?? null)),
                'tls' => match (true) {
                    filled($router['tls.certresolver'] ?? null) => ['certResolver' => $router['tls.certresolver']],
                    strtolower($router['tls'] ?? '') === 'true' => ['options' => 'default'],
                    default => null,
                },
            ];
        }

        return $routers;
    }

    private static function port(Application $application): int
    {
        return $application->settings->is_static ? 80 : (int) ($application->ports_exposes_array[0] ?? 80);
    }
}
